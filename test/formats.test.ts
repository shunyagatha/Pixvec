function buildBmp(bpp: 24 | 32, topDown = false): Buffer {
  const rowSize = Math.ceil((W * bpp) / 32) * 4;
  const pixels = rowSize * H;
  const offset = 54;
  const b = Buffer.alloc(offset + pixels);

  b.write('BM', 0);
  b.writeUInt32LE(offset + pixels, 2);
  b.writeUInt32LE(offset, 10);
  b.writeUInt32LE(40, 14);
  b.writeInt32LE(W, 18);
  b.writeInt32LE(topDown ? -H : H, 22);
  b.writeUInt16LE(1, 26);
  b.writeUInt16LE(bpp, 28);
  b.writeUInt32LE(pixels, 34);

  for (let row = 0; row < H; row++) {
    const srcY = topDown ? row : H - 1 - row;
    for (let x = 0; x < W; x++) {
      const s = (srcY * W + x) * 4;
      const o = offset + row * rowSize + x * (bpp / 8);
      b[o] = REF.data[s + 2];
      b[o + 1] = REF.data[s + 1];
      b[o + 2] = REF.data[s];
      if (bpp === 32) b[o + 3] = 255;
    }
  }
  return b;
}

/** 8-bit palettised BMP; the palette holds every colour the fixture uses. */
function buildIndexedBmp(): { bytes: Buffer; expected: RasterImage } {
  const colors: number[] = [];
  const index = new Map<number, number>();
  const expected = createImage(W, H);

  for (let i = 0; i < W * H; i++) {
    const key = (REF.data[i * 4] << 16) | (REF.data[i * 4 + 1] << 8) | REF.data[i * 4 + 2];
    if (!index.has(key) && index.size < 256) {
      index.set(key, colors.length);
      colors.push(key);
    }
  }

  const paletteCount = colors.length;
  const rowSize = Math.ceil(W / 4) * 4;
  const offset = 54 + paletteCount * 4;
  const b = Buffer.alloc(offset + rowSize * H);

  b.write('BM', 0);
  b.writeUInt32LE(b.length, 2);
  b.writeUInt32LE(offset, 10);
  b.writeUInt32LE(40, 14);
  b.writeInt32LE(W, 18);
  b.writeInt32LE(H, 22);
  b.writeUInt16LE(1, 26);
  b.writeUInt16LE(8, 28);
  b.writeUInt32LE(paletteCount, 46);

  colors.forEach((key, i) => {
    const o = 54 + i * 4;
    b[o] = key & 0xff;             // stored BGRA
    b[o + 1] = (key >> 8) & 0xff;
    b[o + 2] = (key >> 16) & 0xff;
  });

  for (let row = 0; row < H; row++) {
    const srcY = H - 1 - row;
    for (let x = 0; x < W; x++) {
      const s = (srcY * W + x) * 4;
      const key = (REF.data[s] << 16) | (REF.data[s + 1] << 8) | REF.data[s + 2];
      const idx = index.get(key)!;
      b[offset + row * rowSize + x] = idx;
      const c = colors[idx];
      setPixel(expected, x, srcY, (c >> 16) & 0xff, (c >> 8) & 0xff, c & 0xff, 255);
    }
  }
  return { bytes: b, expected };
}

function buildPnm(magic: 'P6' | 'P5' | 'P3', withComment = true): { bytes: Buffer; expected: RasterImage } {
  const comment = withComment ? '# generated by the test suite\n' : '';
  const expected = createImage(W, H);

  if (magic === 'P3') {
    let body = '';
    for (let i = 0; i < W * H; i++) {
      const r = REF.data[i * 4], g = REF.data[i * 4 + 1], bl = REF.data[i * 4 + 2];
      body += `${r} ${g} ${bl}\n`;
      setPixel(expected, i % W, Math.floor(i / W), r, g, bl, 255);
    }
    return { bytes: Buffer.from(`P3\n${comment}${W} ${H}\n255\n${body}`, 'ascii'), expected };
  }

  const channels = magic === 'P6' ? 3 : 1;
  const px = Buffer.alloc(W * H * channels);
  for (let i = 0; i < W * H; i++) {
    if (channels === 3) {
      px[i * 3] = REF.data[i * 4];
      px[i * 3 + 1] = REF.data[i * 4 + 1];
      px[i * 3 + 2] = REF.data[i * 4 + 2];
      setPixel(expected, i % W, Math.floor(i / W), REF.data[i * 4], REF.data[i * 4 + 1], REF.data[i * 4 + 2], 255);
    } else {
      const v = REF.data[i * 4];
      px[i] = v;
      setPixel(expected, i % W, Math.floor(i / W), v, v, v, 255);
    }
  }
  const head = Buffer.from(`${magic}\n${comment}${W} ${H}\n255\n`, 'ascii');
  return { bytes: Buffer.concat([head, px]), expected };
}

function buildTga(opts: { rle?: boolean; topDown?: boolean; depth?: 24 | 32 } = {}): Buffer {
  const { rle = false, topDown = true, depth = 32 } = opts;
  const bpp = depth / 8;
  const body: number[] = [];

  const pixelAt = (i: number): number[] => {
    const srcY = topDown ? Math.floor(i / W) : H - 1 - Math.floor(i / W);
    const s = (srcY * W + (i % W)) * 4;
    const px = [REF.data[s + 2], REF.data[s + 1], REF.data[s]];
    if (depth === 32) px.push(255);
    return px;
  };

  if (rle) {
    // Emit every pixel as its own one-pixel raw packet; correctness of the
    // packet loop is what matters here, not compression ratio.
    for (let i = 0; i < W * H; i++) body.push(0x00, ...pixelAt(i));
  } else {
    for (let i = 0; i < W * H; i++) body.push(...pixelAt(i));
  }

  const b = Buffer.alloc(18 + body.length);
  b[2] = rle ? 10 : 2;
  b.writeUInt16LE(W, 12);
  b.writeUInt16LE(H, 14);
  b[16] = depth;
  b[17] = topDown ? 0x20 : 0x00;
  Buffer.from(body).copy(b, 18);
  return b;
}

async function buildIco(): Promise<Buffer> {
  const png = await sharp(Buffer.from(REF.data.buffer, REF.data.byteOffset, REF.data.byteLength), {
    raw: { width: W, height: H, channels: 4 },
  }).png().toBuffer();

  const b = Buffer.alloc(6 + 16 + png.length);
  b.writeUInt16LE(0, 0);
  b.writeUInt16LE(1, 2);
  b.writeUInt16LE(1, 4);
  b[6] = W;
  b[7] = H;
  b.writeUInt16LE(1, 10);
  b.writeUInt16LE(32, 12);
  b.writeUInt32LE(png.length, 14);
  b.writeUInt32LE(22, 18);
  png.copy(b, 22);
  return b;
}

