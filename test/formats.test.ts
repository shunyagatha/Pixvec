describe('signature detection', () => {
  it('identifies each container', () => {
    expect(isBmp(buildBmp(24))).toBe(true);
    expect(isPnm(buildPnm('P6').bytes)).toBe(true);
    expect(isTga(buildTga())).toBe(true);
  });

  it('does not claim files belonging to other formats', () => {
    const png = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 13]);
    expect(isBmp(png)).toBe(false);
    expect(isPnm(png)).toBe(false);
    expect(isIco(png)).toBe(false);
    expect(isTga(png)).toBe(false);
  });

  it('rejects empty and truncated input', () => {
    for (const buf of [Buffer.alloc(0), Buffer.from('BM'), Buffer.from('P')]) {
      expect(isBmp(buf)).toBe(false);
      expect(isPnm(buf)).toBe(false);
      expect(isTga(buf)).toBe(false);
      expect(isIco(buf)).toBe(false);
    }
  });
});

describe('BMP', () => {
  it.each([[24], [32]] as const)('decodes %ibpp bottom-up exactly', async (bpp) => {
    const { image } = await decodeRaster(buildBmp(bpp));
    expect(compareImages(REF, image).lossless).toBe(true);
  });

  it('honours a negative height as top-down', async () => {
    const { image } = await decodeRaster(buildBmp(24, true));
    expect(compareImages(REF, image).lossless).toBe(true);
  });

  it('decodes an 8-bit palettised image exactly', async () => {
    const { bytes, expected } = buildIndexedBmp();
    const { image } = await decodeRaster(bytes);
    expect(compareImages(expected, image).lossless).toBe(true);
  });

  /**
   * In 32-bit BI_RGB the fourth byte is officially unused, and many encoders
   * leave it at zero. Honouring that literally would make the whole image
   * transparent, so an all-zero alpha channel is treated as opaque.
   */
  it('treats an all-zero alpha channel as opaque', () => {
    const bytes = buildBmp(32);
    const rowSize = Math.ceil((W * 32) / 32) * 4;
    for (let row = 0; row < H; row++) {
      for (let x = 0; x < W; x++) bytes[54 + row * rowSize + x * 4 + 3] = 0;
    }
    const { image } = decodeBmp(bytes);
    expect(image.data[3]).toBe(255);
  });

  it('reports the source format rather than the payload format', async () => {
    const { meta } = await decodeRaster(buildBmp(24));
    expect(meta.format).toBe('bmp');
    expect([meta.width, meta.height]).toEqual([W, H]);
  });

  it('refuses implausible dimensions instead of allocating', () => {
    const b = Buffer.alloc(54);
    b.write('BM', 0);
    b.writeUInt32LE(54, 10);
    b.writeUInt32LE(40, 14);
    b.writeInt32LE(99_999_999, 18);
    b.writeInt32LE(99_999_999, 22);
    b.writeUInt16LE(24, 28);
    expect(() => decodeBmp(b)).toThrow(/Implausible/);
  });
});

describe('Netpbm', () => {
  it.each(['P6', 'P5', 'P3'] as const)('decodes %s exactly', async (magic) => {
    const { bytes, expected } = buildPnm(magic);
    const { image } = await decodeRaster(bytes);
    expect(compareImages(expected, image).lossless).toBe(true);
  });

  it('skips comments wherever they appear', () => {
    const withComment = decodePnm(buildPnm('P6', true).bytes);
    const without = decodePnm(buildPnm('P6', false).bytes);
    expect(compareImages(withComment.image, without.image).lossless).toBe(true);
  });

  it('inverts PBM, where a set bit means black', () => {
    const bytes = Buffer.concat([Buffer.from('P4\n8 1\n', 'ascii'), Buffer.from([0b10000000])]);
    const { image } = decodePnm(bytes);
    expect(Array.from(image.data.slice(0, 4))).toEqual([0, 0, 0, 255]);       // bit set
    expect(Array.from(image.data.slice(4, 8))).toEqual([255, 255, 255, 255]); // bit clear
  });

  it('rejects a malformed header', () => {
    expect(() => decodePnm(Buffer.from('P6\nnot-a-number\n', 'ascii'))).toThrow(/Malformed/);
  });
});

describe('TGA', () => {
  it.each([
    ['32-bit top-down', { depth: 32, topDown: true }],
    ['24-bit top-down', { depth: 24, topDown: true }],
    ['32-bit bottom-up', { depth: 32, topDown: false }],
    ['run-length encoded', { depth: 32, topDown: true, rle: true }],
  ] as const)('decodes %s exactly', async (_name, opts) => {
    const { image } = await decodeRaster(buildTga(opts as never));
    expect(compareImages(REF, image).lossless).toBe(true);
  });

  it('reads the dimensions back', () => {
    const { image } = decodeTga(buildTga());
    expect([image.width, image.height]).toEqual([W, H]);
  });
});

describe('ICO', () => {
  it('decodes a PNG-payload icon exactly', async () => {
    const { image, meta } = await decodeRaster(await buildIco());
    expect(meta.format).toBe('ico');
    expect(compareImages(REF, image).lossless).toBe(true);
  });

  it('lists its entries', async () => {
    const entries = listIcoEntries(await buildIco());
    expect(entries).toHaveLength(1);
    expect(entries[0].isPng).toBe(true);
    expect([entries[0].width, entries[0].height]).toEqual([W, H]);
  });

  it('reads a stored dimension of zero as 256', () => {
    const b = Buffer.alloc(6 + 16 + 8);
    b.writeUInt16LE(1, 2);
    b.writeUInt16LE(1, 4);
    b[6] = 0; // means 256
    b[7] = 0;
    b.writeUInt32LE(8, 14);
    b.writeUInt32LE(22, 18);
    expect(listIcoEntries(b)[0].width).toBe(256);
  });
});

