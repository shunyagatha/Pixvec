import { createImage, setPixel } from './fixtures.js';

/**
 * Formats libvips is not built with, decoded in pure TypeScript.
 *
 * Every case here builds the container by hand and asserts a **bit-exact**
 * decode, because these are all lossless formats: anything less than exact
 * means a byte-order, padding or scan-direction bug. Odd dimensions are used
 * throughout so row padding is always exercised.
 */

const W = 17;
const H = 11;

function reference(): RasterImage {
  const img = createImage(W, H);
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      setPixel(img, x, y, (x * 15) % 256, (y * 23) % 256, ((x + y) * 9) % 256, 255);
    }
  }
  return img;
}

const REF = reference();

