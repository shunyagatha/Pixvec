interface Flatness {
  distinctColors: number;
  capped: boolean;
  /** Horizontal runs per pixel. Near 0 is flat artwork, near 1 is noise. */
  runRatio: number;
  /**
   * Mean absolute deviation from the local mean, measured only AWAY from edges.
   *
   * This is the precondition for sub-pixel refinement, not a content guess.
   * Refinement recovers where an edge fell by inverting the anti-aliasing
   * coverage across it; that inversion assumes the only variation near a
   * boundary IS coverage. Interior noise is variation that is not, and it gets
   * read as edge displacement.
   */
  interiorNoise: number;
}

/**
 * Two cheap signals separate "artwork" from "photograph" reliably:
 * the number of distinct colours, and how often colour changes along a scanline.
 * A screenshot can have thousands of colours yet still be mostly flat; a
 * gradient-heavy photo has both high counts and high run density.
 */
export function measureFlatness(img: RasterImage, colorCap = 4096): Flatness {
  const seen = new Set<number>();
  const d = img.data;
  let runs = 0;
  let capped = false;
  let prev = -1;

  for (let y = 0; y < img.height; y++) {
    prev = -1;
    for (let x = 0; x < img.width; x++) {
      const o = (y * img.width + x) * 4;
      const a = d[o + 3];
      const key = a === 0 ? 0 : packRgba(d[o], d[o + 1], d[o + 2], a);
      if (key !== prev) { runs++; prev = key; }
      if (!capped) {
        seen.add(key);
        if (seen.size > colorCap) capped = true;
      }
    }
  }

  // Second pass, off the edges: how much does a pixel differ from its own
  // neighbourhood where there is no boundary to explain it? Cheap, and the only
  // thing that predicts whether refinement will help or hurt.
  const lum = (x: number, y: number): number => {
    const o = ((y * img.width) + x) * 4;
    return (d[o] + d[o + 1] + d[o + 2]) / 3;
  };
  let noiseSum = 0;
  let noiseN = 0;
  for (let y = 1; y < img.height - 1; y++) {
    for (let x = 1; x < img.width - 1; x++) {
      const gx = lum(x + 1, y) - lum(x - 1, y);
      const gy = lum(x, y + 1) - lum(x, y - 1);
      if (Math.hypot(gx, gy) > 24) continue;   // a real boundary, not interior
      let mean = 0;
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) mean += lum(x + dx, y + dy);
      noiseSum += Math.abs(lum(x, y) - mean / 9);
      noiseN++;
    }
  }

  return {
    distinctColors: seen.size,
    capped,
    runRatio: runs / (img.width * img.height),
    interiorNoise: noiseN > 0 ? noiseSum / noiseN : 0,
  };
}

/**
 * Interior noise above which sub-pixel refinement is switched off.
 *
 * Measured, with the same images clean and re-encoded, so the split is not a
 * content guess:
 *
 *   PNG rendered from vector   0.014 - 0.219   refinement worth +3.01 dB at scale
 *   the same at JPEG q40       0.577 - 1.079   refinement costs 0.03-0.10 SSIM
 *   logo-tux.png               0.799           costs 0.058 SSIM
 *   photo-parrots.png          1.583
 *   a 100x100 JPEG sticker     5.061           costs 0.095 SSIM and 3.6x bytes
 *
 * No overlap: the clean set tops out at 0.219 and the noisy set starts at 0.577.
 * 0.3 sits inside that gap and is deliberately nearer the clean end, because the
 * two mistakes are not symmetric — refining clean input that did not need it
 * costs a little size, while refining noisy input costs accuracy AND 3x the
 * bytes.
 *
 * This replaces a genuinely bad rule. Refinement was previously switched off by
 * `flat.capped`, a >4096 colour count, which JPEG noise trips on a cartoon — so
 * the reported image that motivated curves-by-default went back to zero curves.
 * A colour count is a proxy for content; this is the mechanism's own
 * precondition.
 */
const REFINE_NOISE_LIMIT = 0.3;

function resolveMode(
  input: VectorizeInput,
  opts: VectorizeOptions,
  notes: string[],
): VectorizeMode {
  if (opts.preset === 'pixelart') return 'pixel';
  // `lossless` and the `exact` preset never reach here — `vectorize` routes them
  // to `runLossless`, which decides by measuring candidates rather than guessing.
  if (opts.mode && opts.mode !== 'auto' && opts.mode !== 'lossless') return opts.mode;

  // An explicit preset outranks the auto heuristics.
  //
  // Until now it did not, and the consequence was total rather than subtle: this
  // function read `opts.preset` for exactly two values, `'pixelart'` above and
  // `'exact'` in `vectorize`. Every other preset was consulted only inside
  // `runTrace`, which is never reached when the statistics choose pixel — so
  // `logo`, `lineart`, `poster`, `photo` and `detailed` all produced output
  // *byte-identical to `auto`*. Measured on a rasterised vector original: all five
  // returned the same sha256, the same 40,630 bytes and the same 57 shapes; and on
  // this project's own `logo-tux.png`, `--preset logo` returned a 16 KB base64
  // raster. Naming a tracing preset is a statement that a resolution-independent
  // result is wanted, and it was being ignored.
  //
  // Placed *after* the `opts.mode` check so `--mode pixel --preset logo` still
  // honours the more specific flag, and the note says how to get an exact copy
  // back, because for a flat logo that genuinely is the smaller answer.
  if (opts.preset !== undefined && opts.preset !== 'auto') {
    notes.push(
      `Preset '${opts.preset}' selected trace mode: naming a preset outranks the ` +
        `auto heuristics, which would otherwise have measured this image and may ` +
        `have chosen an exact copy. Use --mode pixel or --mode embed for that.`,
    );
    return 'trace';
  }

  const flat = measureFlatness(input.image, 4096);
  if (isPixelFeasible(input.image, flat)) {
    notes.push(
      `Auto-selected pixel mode: ${flat.distinctColors} distinct colours, ` +
        `${(flat.runRatio * 100).toFixed(1)}% run density. Output is bit-exact.`,
    );
    return 'pixel';
  }

  notes.push(
    `Auto-selected trace mode: ${flat.capped ? '>4096' : flat.distinctColors} distinct colours, ` +
      `${(flat.runRatio * 100).toFixed(1)}% run density. Tracing approximates; ` +
      `use --mode embed if you need this image reproduced exactly.`,
  );
  return 'trace';
}

/** Ceiling on rectangles before a pixel-mode file stops being worth having. */
const PIXEL_RECT_BUDGET = 600_000;
/** Run density below which greedy meshing still folds many pixels per rectangle. */
const FLAT_RUN_RATIO = 0.12;
/** Palette size below which an image is flat artwork whatever its run density. */
const FLAT_COLOR_COUNT = 64;

/**
 * Decide whether pixel mode would produce a file worth having.
 *
 * Two independent signals each indicate genuinely flat content, and either one
 * is enough:
 *
 * - **Long colour runs.** Greedy meshing folds an order of magnitude of pixels
 *   into each rectangle, so the output is real geometry rather than a bitmap
 *   spelled out in `<rect>` elements.
 * - **A small palette.** A 32×32 sprite changes colour every few pixels, so its
 *   run density looks photographic — but four colours across a thousand pixels
 *   is unmistakably artwork, and pixel mode handles it perfectly.
 *
 * Requiring both would push sprites to the tracer, which is exactly wrong: pixel
 * art is the one case where exact output is both achievable and expected.
 * A hard rectangle budget then bounds the cost regardless of which signal fired.
 */
function isPixelFeasible(img: RasterImage, flat: Flatness): boolean {
  if (flat.capped || flat.distinctColors > 4096) return false;

  // `runRatio` counts HORIZONTAL runs, so this product is the rectangle count
  // *before* greedy meshing merges anything vertically — an upper bound, and a
  // deliberately one-sided one. Measured against the real count it is tight:
  // 1.04x-1.62x, median 1.13x across the corpus, with zero images where the
  // bound and the truth land on opposite sides of the budget.
  //
  // It is blind to vertical coherence, and that blindness is unbounded rather
  // than merely loose: 1px-wide alternating stripes at 2000x2000 estimate
  // 4,000,000 against a true 2,000, so a two-colour image whose exact output is
  // 14.8 KB is refused. Left alone deliberately, because nothing realistic
  // reaches it — the input must have runRatio near 1 AND near-perfect vertical
  // coherence at once. Real vertical structure has *few* runs per row, so it is
  // not close: a 3000x1200 barcode estimates 145,200, an A4 ruled form at
  // 400 dpi 109,256, and 1920x1080 colour bars 7,560, all against a 600,000
  // budget. Widening the estimate to min(horizontal, vertical) runs would cost
  // a second cache-hostile pass in what is deliberately a cheap pre-filter, and
  // would trade a measured-tight bound for an unproven one.
  const estimatedRects = flat.runRatio * img.width * img.height;
  if (estimatedRects > PIXEL_RECT_BUDGET) return false;

  return flat.runRatio <= FLAT_RUN_RATIO || flat.distinctColors <= FLAT_COLOR_COUNT;
}

/**
 * Look for an exact result that beats an approximate one outright.
 *
 * Auto mode chooses from colour count and run density, before anything has been
 * produced. Those signals misjudge anti-aliased artwork badly: a logo with 194
 * colours and soft edges reads as "too varied for exact geometry", goes to the
 * tracer, and comes back **eight times larger than the source file and still
 * approximate** — while an embedded copy would have been smaller *and* exact.
 *
 * A user cannot be expected to notice that, so this checks. It only runs when
 * the traced output is already suspiciously large (bigger than the input file),
 * which keeps the extra work off the common path where tracing did its job.
 *
 * The bar is deliberately dominance, not preference: the alternative must be
 * both smaller and bit-exact. Anything less is a genuine trade-off, and those
 * belong to the caller.
 */
/**
 * What `auto` actually optimises for, measured — because three separate
 * investigations have now reached for this question and each assumed a
 * different mechanism.
 *
 * **`auto` never returns a Bézier.** Swept across 39 real images — flat icons,
 * multi-colour logos, alpha-heavy art and photographs — the default produced
 * zero curve commands on every one. Not by one route but by three, which is why
 * it keeps being rediscovered as a new bug:
 *
 * - flat few-colour art goes to `pixel` (30 of 39), which is bit-exact
 *   rectangles — see {@link isPixelFeasible};
 * - richer artwork goes to `trace`, and then this function finds an exact copy
 *   that is smaller *and* bit-exact and takes it (7 of the 9 that reached trace;
 *   on `logo-tux.png`, 16,221 bytes against the trace's 107,926);
 * - what survives as a trace still emits no curves, because at the shipped
 *   `tolerance: 0.4` the fitter does not fire at all.
 *
 * That is a coherent contract, not three bugs: **`auto` optimises for fidelity
 * at the image's own resolution, and resolution independence is the axis it does
 * not weigh.** Every branch above is the right answer to "reproduce this image
 * as faithfully and cheaply as possible" and the wrong answer to "give me
 * something that scales".
 *
 * The redeeming property, also measured: it is never silent. All 39 carried a
 * note naming what happened and how to get curves instead — 0 non-scalable
 * results without an explanation. Keep it that way; a default that quietly
 * hands back a bitmap in an SVG wrapper is the actual defect, not this one
 * choosing exactness.
 *
 * Users who want curves have `--mode trace`, `--preset logo`, or `--tolerance`.
 */
async function findDominatingExact(
  input: VectorizeInput,
  traced: VectorizeResult,
  opts: VectorizeOptions,
  notes: string[],
): Promise<VectorizeResult | null> {
  // A trace that produced real curves is not comparable to a raster on size
  // alone, so it is not "dominated" by one that happens to be smaller.
  //
  // This mattered the moment curves became the default. Refinement makes a trace
  // roughly 2.35x larger gzipped, which pushed far more images over the line
  // here — so switching curves on in the tracer produced *fewer* curves from
  // `auto`, because this function then swapped them for a bitmap. Two tests
  // caught it by expecting 'trace' and getting 'embed'.
  //
  // The original reasoning stands where it applies: when the trace emitted no
  // curve commands at all it is already a bitmap in an SVG wrapper, and an exact
  // copy that is smaller beats it on every axis with nothing to trade. That case
  // still switches, and still says so.
  // TWO THINGS MEASURED HERE AND NOT ACTED ON, so the next reader does not
  // re-derive them.
  //
  // 1. This compares RAW bytes, and raw systematically favours the embed: base64
  //    is incompressible while path data gzips about 5x. On alpha-dice the two
  //    disagree by 3.9x in opposite directions — raw picks embed (318.0 vs 292.7
  //    KB), gzip picks trace (56.3 vs 219.2 KB). Measured across 13 images the
  //    decision changes on 1 of them, so this is real but rare, and "what ships"
  //    is genuinely ambiguous — raw is the file on disk, gzip is the bytes on the
  //    wire. Not changed on a 1-in-13 effect with no clearly right answer.
  //
  // 2. The deeper issue is the objective, not the units. This function weighs
  //    size and exactness. A vector's value is that it SCALES, and that is not in
  //    the comparison at all — so a bit-exact raster will always look like it
  //    dominates a trace of similar size, for a tool whose purpose is to produce
  //    geometry. On the reported 100x100 sticker the embed really is smaller
  //    (10.7 vs 11.1 KB gzipped) and really is bit-exact, and returning it is
  //    still arguably the wrong answer to "vectorise this".
  //
  const tracedCurves = [...traced.svg.matchAll(/\sd="([^"]*)"/g)]
    .reduce((n, m) => n + (m[1].match(/[CcSsQqTtAa]/g) ?? []).length, 0);
  if (tracedCurves > 0) return null;

  const tracedBytes = Buffer.byteLength(traced.svg);
  const tracedGzip = gzipBytes(traced.svg);
  // Someone who typed `convert x.jpg x.svg` asked for geometry; `--mode embed`
  // exists and is named for the other thing. So real paths are kept unless the
  // exact raster is dramatically smaller, not merely smaller.
  const geometryRatio = opts.maxGeometryRatio ?? 4;
  // `meta` is required by the type, but plain-JS callers reach here through the
  // CJS build with `vectorize({ image })` — which works for the pixel and embed
  // paths and then crashes here, only when auto happens to pick trace. Nothing
  // downstream needs the comparison if we do not know the source size.
  if (input.meta === undefined || tracedBytes <= input.meta.bytes) return null;

  try {
    // `preserve` first because it is smaller and keeps the original file, then
    // `png` which always renders exactly. Asking for `auto` here would be a
    // trap: on a JPEG source it picks the preserved payload, which is smaller
    // but *not* bit-exact through the renderer, so the check would find no
    // dominating candidate and silently keep the worse traced result.
    let exact: Awaited<ReturnType<typeof vectorizeEmbed>> | null = null;
    let exactBytes = 0;
    let report: QualityReport | null = null;

    for (const strategy of ['preserve', 'png'] as const) {
      const candidate = await vectorizeEmbed(input.image, input.bytes, input.meta, {
        ...opts.embed, strategy,
        generator: opts.noGenerator ? undefined : GENERATOR,
        title: opts.title,
      });
      // Judged on SHIPPED bytes, and with a margin.
      //
      // Raw byte counts favour the raster twice over: base64 does not compress,
      // while path data gzips about 5x, so a trace that is smaller on the wire
      // looks larger on disk. On alpha-dice the two disagree by 3.9x in opposite
      // directions. Comparing what the user actually receives removes that.
      //
      // The margin is the substantive part. This used to swap on ANY win — a
      // trace was discarded for a raster 0.4 KB smaller, trading away the one
      // property a vector has. `maxGeometryRatio` already expresses exactly this
      // trade for `lossless` mode; auto had no such guard and should.
      const bytes = gzipBytes(candidate.svg);
      if (bytes * geometryRatio >= tracedGzip) continue;

      const measured = await verifySvg(candidate.svg, input.image, opts.compare);
      if (!measured.lossless) continue;

      exact = candidate;
      exactBytes = bytes;
      report = measured;
      break;
    }

    if (!exact || !report) return null;

    // The accuracy clause is conditional because the accuracy is usually
    // unknown here. `quality` is only populated when the caller asked to
    // verify, and this runs before that — so the previous unconditional
    // `traced.quality?.ssim ?? 0` printed "SSIM 0.0000" on the default
    // `convert` path for every input it rejected. Identical bytes, identical
    // decision, and a figure that was the fallback rather than a measurement:
    // the same trace scores 0.988411 when actually verified.
    //
    // Measuring it here to fill the sentence would mean rendering and scoring
    // an SVG we are about to discard, on the common path, to print a number
    // that decides nothing — the choice below is byte-dominance, not accuracy.
    // So say what is known instead.
    const accuracy = traced.quality ? ` at SSIM ${traced.quality.ssim.toFixed(4)}` : '';
    notes.push(
      `Switched to embed: tracing produced ${formatCount(tracedGzip)} bytes gzipped${accuracy}, ` +
        `while an exact copy is ${formatCount(exactBytes)} — more than ${geometryRatio}x ` +
        `smaller, and bit-exact. Below that margin the geometry is kept, because ` +
        `scaling is what it is for. Use --mode trace to force ` +
        `real curves.`,
    );

    return {
      svg: exact.svg,
      width: input.image.width,
      height: input.image.height,
      mode: 'embed',
      shapes: 1,
      colors: 0,
      lossless: true,
      quality: report,
      notes,
      elapsedMs: 0,
      settled: {
        mime: exact.mime,
        payloadBytes: exact.payloadBytes,
        bytesPreserved: exact.bytesPreserved,
        rejectedTraceBytes: tracedBytes,
      },
    };
  } catch {
    // The comparison is an optimisation; failing it just keeps the traced result.
    return null;
  }
}

