/**
 * Trace, then — if a quality target was given — escalate and try again.
 *
 * Each step doubles the palette and tightens the geometric tolerances, because
 * the two failure modes are different: too few colours shows up as banding,
 * too loose a tolerance shows up as rounded-off detail. Moving both keeps the
 * search short. The best result seen is kept, so a target that turns out to be
 * unreachable still returns the closest attempt rather than the last one.
 */
/**
 * When no preset is named, scale the trace settings to the content instead of
 * always using the lean 16-colour default. A photograph traced with 16 colours
 * bands visibly; a zero-config `convert photo.png out.svg` should give it a
 * photo-grade palette and gradient de-banding (which can only help). Flat artwork
 * keeps the lean default, which is already ideal — and is never sent here anyway,
 * since auto mode routes it to bit-exact pixel output first.
 */
function autoTracePreset(img: RasterImage, notes: string[]): TraceOptions {
  const flat = measureFlatness(img, 4096);

  // Sub-pixel refinement runs only where its own precondition holds.
  //
  // It recovers where an edge fell by inverting the anti-aliasing coverage
  // across it, which assumes the variation near a boundary IS coverage. Feed it
  // a noisy source and it inverts the noise, displacing vertices to where no
  // edge was. That is not a small effect: on the same images clean and at JPEG
  // q40, the accuracy it costs grows 10-25x (-0.003 SSIM clean, -0.032 to
  // -0.095 noisy) while it keeps charging 2.3-3.7x the bytes.
  //
  // Deliberately NOT a content-type guess. Two of those were tried and both
  // failed: a >4096 colour count put a JPEG cartoon in the same bucket as a
  // photograph, and a flat-neighbourhood share ranked that cartoon (11.3%)
  // below a genuine photograph (12.5%). `interiorNoise` measures the thing the
  // algorithm actually needs, and separates cleanly — see REFINE_NOISE_LIMIT.
  const refine: TraceOptions = {};
  if (flat.interiorNoise > REFINE_NOISE_LIMIT) {
    refine.subpixel = false;
    // The lattice straightness test fails on the same precondition, and it is
    // worth being explicit that this is one condition rather than two.
    //
    // Both assume a boundary came from a real geometric edge that the pixel grid
    // quantised. Sub-pixel refinement inverts the coverage ramp across such an
    // edge; the straightness test asks whether a run of vertices could have come
    // from one. Continuous tone has no such edges, so the first inverts noise and
    // the second finds spurious straightness in it — measured on the published
    // photo row, leaving it on took `trace auto` from 49.3 KB to 163.8 KB while
    // SSIM fell 0.8476 -> 0.8311. Worse and 3.3x larger.
    // Both stay off, and the second one is a conclusion I reached twice and had to
    // measure twice.
    //
    // The argument for re-enabling boundary simplification here is that `segment`
    // does not merely tolerate noise, it removes it — so the precondition is
    // established downstream rather than absent. That argument is wrong, because
    // the precondition is not "no noise", it is "this boundary came from a
    // straight geometric edge that the grid quantised". Segmentation removes grain;
    // it does not make a photograph's region boundaries straight. They are organic,
    // and a straightness test run over them manufactures a curve at every bend.
    //
    // Measured with segmentation on, against leaving simplification off:
    //
    //   sticker   0.9556 ->  0.8849 SSIM,   9.9 ->  15 KB,  3,894 curves
    //   logo-tux  0.9731 ->  0.9319 SSIM,  14.4 ->  25 KB,  4,724 curves
    //   parrots   ~0.81   ->  0.8174 SSIM,   72 -> 196 KB, 24,065 curves
    //
    // Worse on accuracy AND size on all three. Widening the band does not rescue
    // it either — 0.75 through 6.0 costs more accuracy and more bytes at every
    // step, up to 314 KB on the photograph. Curves are available on demand and are
    // not worth this by default.
    refine.latticeSimplify = false;
    notes.push(
      `Sub-pixel refinement and lattice simplification off: interior noise ` +
        `${flat.interiorNoise.toFixed(2)} exceeds ${REFINE_NOISE_LIMIT}, so there is no ` +
        `quantised geometric edge for either to read. Force them with --subpixel and ` +
        `--lattice-simplify if the source is cleaner than it measures.`,
    );
  }
  // Only the palette is widened (plus gradient de-banding for photos). minArea
  // and the fit tolerances are deliberately left to auto-scale: forcing a larger
  // minArea here despeckled fine detail — feathers, foliage — and cost more
  // accuracy than the extra colours bought back.
  if (flat.capped) {
    // Sub-pixel refinement STAYS ON here, and the story of why is worth keeping.
    //
    // It was switched off for photographs on the strength of the published bench
    // row: 49.3 -> 93.8 KB, 31.31 -> 30.82 dB, 0.8476 -> 0.8116 SSIM. Every axis
    // worse. But that row scores the output against the SOURCE at 1x, and at 1x
    // the lattice cannot lose — it *is* the source, resampled. The measurement
    // was circular, and so was the conclusion drawn from it. Re-measuring at
    // 3.902x against a Lanczos upscale reproduced the same false result for the
    // same reason: an upscale is derived from the bitmap too.
    //
    // The only non-circular instrument here is `bench:scale` against real vector
    // originals, where the truth is a shape the tracer never saw. It says
    // refinement is worth +3.01 dB on 300 real logos, and the current default
    // holds 17.26 dB with 2,549 curves at 100% detail on corpus/src.
    //
    // A tracer's job is to recover a resolution-independent shape. Callers who
    // want the input reproduced have `pixel`, `embed` and `lossless`, all of
    // which are bit-exact and none of which guess.
    notes.push('Auto-tuned trace for photographic content: 48-colour palette with gradient de-banding.');
    return { colors: 48, gradients: true, ...refine };
  }

  if (flat.distinctColors > FLAT_COLOR_COUNT) {
    notes.push(`Auto-tuned trace for rich colour (${flat.distinctColors} colours): 32-colour palette.`);
    return { colors: 32, ...refine };
  }
  return { ...refine };
}

async function runTrace(
  input: VectorizeInput,
  opts: VectorizeOptions,
  generator: string | undefined,
  notes: string[],
): Promise<VectorizeResult> {
  const preset = opts.preset && opts.preset !== 'auto' && opts.preset in PRESETS
    ? PRESETS[opts.preset as keyof typeof PRESETS]
    : autoTracePreset(input.image, notes);

  const base: TraceOptions = {
    ...TRACE_DEFAULTS,
    // Ahead of the spreads so a caller can still pass its own, or null to opt
    // out. Without it an oversized image ends the process with a V8 heap dump
    // instead of a sentence naming three ways forward.
    loopBudget: heapLoopBudget(),
    ...preset,
    ...stripUndefined(opts.trace ?? {}),
    generator,
    title: opts.title,
  };

  const targetSsim = opts.targetSsim;
  const targetPsnr = opts.targetPsnr;
  const hasTarget = targetSsim !== undefined || targetPsnr !== undefined;
  const maxColors = Math.min(256, opts.maxColors ?? 256);
  const maxSteps = opts.maxRefineSteps ?? 6;

  // A size budget is the inverse search — relax until it fits — so it runs its
  // own loop. Asking to grow quality *and* shrink the file at once is
  // contradictory; the budget is the binding constraint and says what it cost.
  if (opts.maxBytes !== undefined || opts.maxNodes !== undefined) {
    if (hasTarget) {
      notes.push('A size budget and a quality target were both given; the budget binds, and the accuracy it cost is reported.');
    }
    // Each step is a trace but only the baseline and the settled result are
    // rendered, so eight measure-only steps are cheap. A direct bisection needs
    // about six to converge; four (the old default, tuned for the old expand-
    // then-bisect) left a 200 KB target overshooting to 127 KB.
    return runBudget(input, base, opts, notes, opts.maxRefineSteps ?? 8);
  }

  let current: TraceOptions = { ...base };
  let best: { out: ReturnType<typeof trace>; report?: QualityReport; opts: TraceOptions } | null = null;
  let steps = 0;

  for (;;) {
    steps++;
    const out = trace(input.image, current);

    if (!hasTarget) {
      return traceResult(input, out, current, notes, undefined);
    }

    const report = await verifySvg(out.svg, input.image, opts.compare);
    const better = !best?.report || report.ssim > best.report.ssim;
    if (better) best = { out, report, opts: current };

    const ssimOk = targetSsim === undefined || report.ssim >= targetSsim;
    const psnrOk = targetPsnr === undefined || report.psnr >= targetPsnr;
    if (ssimOk && psnrOk) {
      notes.push(`Reached target in ${steps} step${steps === 1 ? '' : 's'}.`);
      return traceResult(input, out, current, notes, report);
    }

    const next = escalate(current, maxColors);
    if (!next || steps >= maxSteps) {
      notes.push(
        `Stopped after ${steps} step${steps === 1 ? '' : 's'} without reaching the target ` +
          `(best mean SSIM ${best!.report!.ssim.toFixed(4)}). Tracing cannot represent every ` +
          `image exactly — use --mode embed if the target is non-negotiable.`,
      );
      return traceResult(input, best!.out, best!.opts, notes, best!.report);
    }
    current = next;
  }
}

/**
 * Trace under a size/complexity budget, and report what it cost.
 *
 * The mirror of the quality-target loop: instead of escalating until accuracy
 * is high enough, this relaxes until the file is small enough — then renders
 * both the unconstrained and the final result so the caller is told, in SSIM,
 * exactly what the smaller file bought. A budget without that receipt would be
 * the opaque simplification slider every other tracer already ships.
 *
 * Intermediate steps are measured on bytes/nodes alone (cheap, no render); only
 * the baseline and the settled result are rendered.
 */
async function runBudget(
  input: VectorizeInput,
  base: TraceOptions,
  opts: VectorizeOptions,
  notes: string[],
  maxSteps: number,
): Promise<VectorizeResult> {
  const targetBytes = opts.maxBytes;
  const targetNodes = opts.maxNodes;
  const fits = (c: SvgComplexity): boolean =>
    (targetBytes === undefined || c.bytes <= targetBytes) &&
    (targetNodes === undefined || c.nodes <= targetNodes);

  const baseOut = trace(input.image, base);
  const baseline = measureSvgComplexity(baseOut.svg);
  const baselineReport = await verifySvg(baseOut.svg, input.image, opts.compare);

  let current: TraceOptions = { ...base };
  let out = baseOut;
  let complexity = baseline;
  let steps = 0;

  if (!fits(baseline)) {
    // Relaxation is a single continuous strength `t`, and `relaxBy` is now
    // monotone and cliff-free in it (see there), so the search is a plain
    // bisection: find the *least* relaxation that still meets the budget, which
    // is the most accurate result that fits.
    //
    // The old version expanded through a fixed ladder [0.25, 0.5, 0.75, 1] and
    // only then bisected. On a four-step budget the ladder ate most of the
    // steps and the bisection never converged — a 200 KB target settled at
    // 127 KB, a 40% overshoot, because the search ran out of moves before it
    // could tighten. A direct bisection spends every step narrowing the bracket.
    let lo = 0;          // known not to fit (the baseline is over budget)
    let hi = -1;         // smallest t known to fit
    let hiOut: ReturnType<typeof trace> | null = null;
    let hiOpts: TraceOptions | null = null;
    let hiComplexity: SvgComplexity | null = null;

    const attempt = (t: number): boolean => {
      const o = relaxBy(base, t);
      const r = trace(input.image, o);
      const c = measureSvgComplexity(r.svg);
      steps++;
      if (fits(c)) {
        if (hi < 0 || t < hi) { hi = t; hiOut = r; hiOpts = o; hiComplexity = c; }
        return true;
      }
      lo = Math.max(lo, t);
      return false;
    };

    // Maximum relaxation first: if even that does not fit, the budget is below
    // what these levers can reach and there is no point bisecting.
    attempt(1);

    // Bisect the [lo, hi] bracket — lo fails, hi fits — for the tightest fit the
    // step budget allows. A floor of 0.02 in `t` is finer than the byte
    // granularity of any single trace, so stopping there costs nothing real.
    while (hi > 0 && steps < maxSteps && hi - lo > 0.02) {
      attempt((lo + hi) / 2);
    }

    if (hiOut) {
      out = hiOut;
      current = hiOpts!;
      complexity = hiComplexity!;
    } else {
      // Nothing fit; return the smallest we produced rather than the baseline.
      current = relaxBy(base, 1);
      out = trace(input.image, current);
      complexity = measureSvgComplexity(out.svg);
    }
  }

  const met = fits(complexity);
  // Re-render only if we actually moved, so an already-fitting image pays once.
  const report = steps === 0
    ? baselineReport
    : await verifySvg(out.svg, input.image, opts.compare);

  const budget: SizeBudgetReport = {
    targetBytes, targetNodes,
    bytes: complexity.bytes, nodes: complexity.nodes,
    met, steps,
    baselineBytes: baseline.bytes, baselineNodes: baseline.nodes,
    baselineSsim: baselineReport.ssim,
    ssim: report.ssim,
    ssimCost: report.ssim - baselineReport.ssim,
  };

  notes.push(
    met
      ? `Met the budget in ${steps} step${steps === 1 ? '' : 's'}: ` +
        `${baseline.bytes}→${complexity.bytes} bytes, ${baseline.nodes}→${complexity.nodes} nodes, ` +
        `for ${(budget.ssimCost ?? 0) >= 0 ? 'no' : `${Math.abs(budget.ssimCost!).toFixed(4)}`} SSIM.`
      : `Could not reach the budget after ${steps} step${steps === 1 ? '' : 's'} — ` +
        `smallest was ${complexity.bytes} bytes / ${complexity.nodes} nodes. ` +
        'Relaxing further would discard structure, so the closest result is returned.',
  );

  const result = traceResult(input, out, current, notes, report);
  result.budget = budget;
  return result;
}

/**
 * Relaxation as a single continuous strength — the inverse of {@link escalate},
 * but parameterised so the budget search can bisect it.
 *
 * `t = 0` is the caller's settings untouched; `t = 1` is as coarse as this will
 * go. All three levers move together because they remove different things:
 * loosening the fit drops anchor points along a curve, absorbing specks drops
 * whole tiny regions, and trimming the palette merges regions outright.
 */
function relaxBy(base: TraceOptions, t: number): TraceOptions {
  const k = 1 + t * 7; // fit tolerance grows up to 8×
  // The levers are *staged*, not fired together, because they cost different
  // things and — this is the part an earlier version got wrong — because a
  // structural lever is *discontinuous*. Dropping specks or palette entries
  // collapses the file in one jump: on a photograph, `minArea` reaching ~20
  // took the byte count from 319 KB straight to 62 KB, a 5× cliff with nothing
  // in between. A budget that landed in that gap could not be hit at all — the
  // bisection would settle on 62 KB for a 120 KB target and pay accuracy it
  // never needed.
  //
  // So the two cheap, *continuous* levers run first and do as much as they can
  // before any structural one engages:
  //
  //   1. Curve-fit tolerance — spends sub-pixel precision along a curve.
  //   2. Coordinate precision — rounds path coordinates, shrinking bytes
  //      smoothly (each dropped decimal is ~15–25% fewer bytes) while deleting
  //      no structure at all. This is what fills the cliff.
  //
  // Only once those are exhausted do the structural levers start:
  //
  //   3. Speckle — absorbs whole small regions.
  //   4. Palette — merges regions by trimming colours.
  const basePrec = base.precision ?? 2;
  // Precision falls from its base toward 0 across the middle of the range, so it
  // is carrying the load exactly where the old curve fell off a cliff.
  const precDrop = Math.max(0, Math.min(1, (t - 0.2) / 0.35));
  const precision = Math.max(0, Math.round(basePrec - precDrop * basePrec));
  const speckle = Math.max(0, (t - 0.55) / 0.45); // idle until t = 0.55 (was 0.4)
  const palette = Math.max(0, (t - 0.75) / 0.25); // idle until t = 0.75 (was 0.6)
  return {
    ...base,
    tolerance: Math.min(8, (base.tolerance ?? 0.4) * k),
    fitError: Math.min(8, (base.fitError ?? 0.4) * k),
    precision,
    minArea: Math.round((base.minArea ?? 0) + speckle * 64),
    colors: Math.max(2, Math.round((base.colors ?? 16) * (1 - 0.6 * palette))),
  };
}

/** Return the next, more aggressive parameter set, or null when maxed out. */
function escalate(o: TraceOptions, maxColors: number): TraceOptions | null {
  const colors = Math.min(maxColors, Math.round((o.colors ?? 16) * 2));
  const tolerance = Math.max(0.05, (o.tolerance ?? 1) * 0.6);
  const fitError = Math.max(0.05, (o.fitError ?? 1) * 0.6);
  const minArea = Math.max(0, Math.floor((o.minArea ?? 0) / 2));

  const exhausted =
    colors === o.colors && tolerance === o.tolerance &&
    fitError === o.fitError && minArea === o.minArea;
  if (exhausted) return null;

  return { ...o, colors, tolerance, fitError, minArea };
}

function traceResult(
  input: VectorizeInput,
  out: ReturnType<typeof trace>,
  settled: TraceOptions,
  notes: string[],
  report: QualityReport | undefined,
): VectorizeResult {
  if (out.despeckled > 0) {
    notes.push(`Absorbed ${out.despeckled} speck${out.despeckled === 1 ? '' : 's'} below --min-area.`);
  }
  return {
    svg: out.svg,
    width: input.image.width,
    height: input.image.height,
    mode: 'trace',
    shapes: out.shapes,
    colors: out.colors,
    lossless: report?.lossless ?? false,
    quality: report,
    notes,
    elapsedMs: 0,
    settled: {
      colors: settled.colors ?? TRACE_DEFAULTS.colors,
      tolerance: settled.tolerance ?? TRACE_DEFAULTS.tolerance,
      fitError: settled.fitError ?? TRACE_DEFAULTS.fitError,
      cornerAngle: settled.cornerAngle ?? TRACE_DEFAULTS.cornerAngle,
      minArea: settled.minArea ?? TRACE_DEFAULTS.minArea,
      regions: out.regions,
    },
  };
}

