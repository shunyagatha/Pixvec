export interface RasterizeToBufferOptions extends RasterizeOptions {
  encode: EncodeOptions;
}

export interface RasterizeOutcome {
  buffer: Buffer;
  width: number;
  height: number;
  intrinsic: { width: number; height: number };
  inlined: string[];
  /** Present when `verify` was requested: the encoded file re-read and compared. */
  quality?: QualityReport;
}

/**
 * Render an SVG and encode it.
 *
 * When `verify` is set, the *encoded* bytes are decoded again and compared
 * against the render. That catches the failure people actually hit — asking for
 * a JPEG and silently losing the alpha channel, or a lossy WebP quality setting
 * doing more damage than expected.
 */
export async function rasterize(
  svg: string | Uint8Array,
  opts: RasterizeToBufferOptions,
  verify = false,
): Promise<RasterizeOutcome> {
  const { image, intrinsic, inlined } = await rasterizeSvg(svg, opts);
  const buffer = await encodeRaster(image, opts.encode);

  const outcome: RasterizeOutcome = {
    buffer,
    width: image.width,
    height: image.height,
    intrinsic,
    inlined,
  };

  if (verify) {
    const roundTrip = await decodeRaster(buffer, { applyOrientation: false });
    outcome.quality = compareImages(image, roundTrip.image);
  }

  return outcome;
}

/** Read either a raster or an SVG and produce comparable RGBA pixels. */
export async function loadAnyAsRaster(
  bytes: Uint8Array,
  path: string | undefined,
  rasterizeOpts?: RasterizeOptions,
): Promise<{ image: RasterImage; kind: 'raster' | 'svg'; meta?: SourceMeta }> {
  if (looksLikeSvg(bytes)) {
    const { image } = await rasterizeSvg(bytes, rasterizeOpts);
    return { image, kind: 'svg' };
  }
  const { image, meta } = await decodeRaster(bytes);
  return { image, kind: 'raster', meta };
}

export function suggestTitle(path: string): string {
  return basename(path).replace(/\.[^.]+$/, '');
}

function stripUndefined<T extends object>(obj: T): Partial<T> {
  const out: Partial<T> = {};
  for (const [k, v] of Object.entries(obj)) {
    if (v !== undefined) (out as Record<string, unknown>)[k] = v;
  }
  return out;
}

/**
 * Group digits the same way everywhere.
 *
 * `toLocaleString()` follows the machine's locale, so the same build prints
 * "236,034" on one developer's box and "2,36,034" on another's. Diagnostic
 * output should not depend on where it runs.
 */
function formatCount(n: number): string {
  return n.toLocaleString('en-US');
}
