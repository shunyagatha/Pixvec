export const VERSION = '0.1.0';

const GENERATOR = `Generated by vexel v${VERSION}`;

export type VectorizeModeOption = VectorizeMode | 'auto' | 'lossless';

export type Preset = 'auto' | 'logo' | 'lineart' | 'poster' | 'photo' | 'detailed' | 'pixelart' | 'exact';

/**
 * Presets are starting points, not straitjackets — every field stays
 * overridable. They exist because the useful parameter combinations cluster by
 * *what kind of picture it is*, and asking someone to guess a Douglas–Peucker
 * tolerance is a bad interface.
 */
export const PRESETS: Record<Exclude<Preset, 'auto' | 'pixelart' | 'exact'>, TraceOptions> = {
  logo: { colors: 16, minArea: 8, tolerance: 1.0, fitError: 1.0, cornerAngle: 75 },
  lineart: { colors: 6, minArea: 4, tolerance: 0.8, fitError: 0.8, cornerAngle: 60 },
  poster: { colors: 32, minArea: 12, tolerance: 1.2, fitError: 1.2, cornerAngle: 80 },
  photo: { colors: 64, minArea: 16, tolerance: 1.4, fitError: 1.4, cornerAngle: 90 },
  detailed: { colors: 48, minArea: 2, tolerance: 0.5, fitError: 0.5, cornerAngle: 60 },
};

export interface VectorizeOptions {
  /**
   * `auto` inspects the image and picks. `lossless` guarantees a bit-exact
   * result, preferring real geometry (`pixel`) and falling back to `embed`.
   */
  mode?: VectorizeModeOption;
  preset?: Preset;
  /** Render the result and measure it against the input. */
  verify?: boolean;
  /** Escalate trace settings until mean SSIM reaches this. Implies `verify`. */
  targetSsim?: number;
  /** Escalate trace settings until PSNR reaches this many dB. Implies `verify`. */
  targetPsnr?: number;
  /** Upper bound on palette size during refinement. */
  maxColors?: number;
  /** Refinement attempts before giving up and returning the best so far. */
  maxRefineSteps?: number;
  trace?: TraceOptions;
  embed?: EmbedOptions;
  pixel?: PixelVectorizeOptions;
  compare?: CompareOptions;
  /** `<title>` for the generated document. */
  title?: string;
  /** Suppress the generator comment. */
  noGenerator?: boolean;
}

export interface VectorizeInput {
  image: RasterImage;
  meta: SourceMeta;
  bytes: Buffer;
}

/** Read and normalise a raster file. */
export async function loadRaster(
  path: string | Buffer,
  opts?: DecodeOptions,
): Promise<VectorizeInput> {
  const { image, meta, bytes } = await decodeRaster(path, opts);
  return { image, meta, bytes };
}

/**
 * Convert a raster image to SVG.
 *
 * The returned `quality` field, when verification runs, is measured against the
 * actual rendered output — not estimated from the parameters. If it says the
 * result is lossless, the file was rendered and compared pixel by pixel.
 */
export async function vectorize(
  input: VectorizeInput,
  opts: VectorizeOptions = {},
): Promise<VectorizeResult> {
  const started = Date.now();
  const notes: string[] = [];
  const generator = opts.noGenerator ? undefined : GENERATOR;
  const wantsTarget = opts.targetSsim !== undefined || opts.targetPsnr !== undefined;
  const verify = opts.verify || wantsTarget;

  const mode = resolveMode(input, opts, notes);

  let result: VectorizeResult;
  switch (mode) {
    case 'embed':
      result = await runEmbed(input, opts, generator, notes);
      break;
    case 'pixel':
      result = runPixel(input, opts, generator, notes);
      break;
    case 'trace':
      result = await runTrace(input, opts, generator, notes);
      break;
  }

  if (verify && !result.quality) {
    result.quality = await verifySvg(result.svg, input.image, opts.compare);
  }

  // Measurement outranks assertion. A mode can be lossless by construction and
  // still not round-trip through a particular renderer — an embedded JPEG is the
  // usual case, where the payload survives intact but the renderer's decoder
  // rounds differently. Reporting the construction-time claim when a measurement
  // contradicts it would be the one lie this tool must not tell.
  if (result.quality) {
    if (!result.quality.lossless && result.lossless) {
      notes.push(
        `Verification found ${result.quality.pixels - result.quality.exactPixels} ` +
          `differing pixel(s) (max ${result.quality.maxChannelDiff}/255). The mode is ` +
          `exact by construction, so this is the renderer's decoder, not lost data.`,
      );
    }
    result.lossless = result.quality.lossless;
  }

  result.elapsedMs = Date.now() - started;
  result.notes = notes;
  return result;
}

/** Render an SVG at the reference image's exact size and compare the two. */
export async function verifySvg(
  svg: string,
  reference: RasterImage,
  compare?: CompareOptions,
  rasterizeOpts?: RasterizeOptions,
): Promise<QualityReport> {
  let rendered = await rasterizeSvg(svg, { ...rasterizeOpts });
  if (rendered.image.width !== reference.width || rendered.image.height !== reference.height) {
    // Force the exact reference size; an off-by-one from unit resolution would
    // otherwise make the comparison impossible rather than merely imprecise.
    rendered = await rasterizeSvg(svg, { ...rasterizeOpts, width: reference.width });
  }
  return compareImages(reference, rendered.image, compare);
}

