/**
 * Bytes the user actually receives, not bytes on disk.
 *
 * The comparison this feeds is between path data and base64. Base64 is
 * incompressible; path data gzips about 5x. Judging them raw therefore hands the
 * raster a systematic advantage it does not have in transit — measured, the two
 * disagree by 3.9x in opposite directions on alpha-dice.
 *
 * `level: 6` is the default most servers use, so this estimates what is actually
 * served rather than the best case.
 */
function gzipBytes(svg: string): number {
  return gzipSync(Buffer.from(svg), { level: 6 }).length;
}


